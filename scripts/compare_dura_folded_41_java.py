"""Create/compare a 41-cubed folded-cortex Dura TGDM Java reference."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import nibabel as nib
import numpy as np
from skimage.measure import marching_cubes

from pymacruise.toads_dura import dura_tgdm_evolve
from pymacruise.validation import dice_coefficient, mesh_surface_distance_metrics


ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests/data/synthetic/dura_tgdm_folded_cortex_41"
SHAPE = (41, 41, 41)
AFFINE = np.eye(4, dtype=np.float64)


def fields() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    x, y, z = np.indices(SHAPE, dtype=np.float64)
    center = tuple((size - 1.0) / 2.0 for size in SHAPE)
    dx, dy, dz = x - center[0], y - center[1], z - center[2]
    radius = np.sqrt(dx * dx + dy * dy + dz * dz)
    theta = np.arctan2(dy, dx)
    polar = np.arccos(np.divide(dz, radius, out=np.zeros_like(radius), where=radius != 0))
    polar[radius == 0] = 0.0
    folds = 1.15 * np.sin(7.0 * theta) * np.sin(4.0 * polar) + 0.45 * np.cos(
        5.0 * theta + 0.7
    ) * np.sin(3.0 * polar)
    outer = (radius - (8.0 + folds)).astype(np.float32)
    inner = (radius - (4.8 + 0.52 * folds)).astype(np.float32)
    gray = (118.0 + 42.0 * np.sin(0.24 * x + 0.16 * y) + 35.0 * np.cos(0.19 * y - 0.21 * z)).astype(np.float32)
    return outer, inner, gray


def save_volume(path: Path, values: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    nib.save(nib.Nifti1Image(np.asarray(values, dtype=np.float32), AFFINE), path)


def load_volume(path: Path) -> np.ndarray:
    image = nib.load(path)
    if image.shape != SHAPE or nib.aff2axcodes(image.affine) != ("R", "A", "S"):
        raise ValueError(f"{path} must be a 41^3 RAS NIfTI")
    return np.asarray(image.dataobj, dtype=np.float32)


def import_java_json(path: Path) -> None:
    reference = json.loads(path.read_text())
    if reference.get("dims") != list(SHAPE) or reference.get("phantom") != "folded_cortex":
        raise ValueError("Java reference must be the 41^3 folded-cortex case")
    if "local DistanceFieldyh" not in reference.get("source", ""):
        raise ValueError("Java reference must identify the selected source distance-field adapter")
    outer, inner, gray = fields()
    save_volume(FIXTURE / "inputs/outer_level_set.nii.gz", outer)
    save_volume(FIXTURE / "inputs/inner_level_set.nii.gz", inner)
    save_volume(FIXTURE / "inputs/gray_matter.nii.gz", gray)
    refs = FIXTURE / "java_reference"
    for index, values in enumerate(reference["pre_reinitialization_passes"], start=1):
        save_volume(refs / f"pass_{index:02d}_pre_reinitialization.nii.gz", np.asarray(values).reshape(SHAPE))
    for index, values in enumerate(reference["passes"], start=1):
        save_volume(refs / f"pass_{index:02d}.nii.gz", np.asarray(values).reshape(SHAPE))
    save_volume(refs / "final.nii.gz", np.asarray(reference["final"]).reshape(SHAPE))
    provenance = {key: value for key, value in reference.items() if key not in {"pre_reinitialization_passes", "passes", "initial_point_update", "final"}}
    provenance.update({
        "provenance": "analytic synthetic folded-cortex phantom; no subject data",
        "coordinate_system": "RAS",
        "affine_ras_mm": AFFINE.tolist(),
        "inputs": ["inputs/outer_level_set.nii.gz", "inputs/inner_level_set.nii.gz", "inputs/gray_matter.nii.gz"],
        "java_reference_volumes": "java_reference/*.nii.gz",
        "conversion_source": "selected Java harness JSON generated by scripts/generate_java_dura_tgdm_full_evolution_reference.sh",
    })
    FIXTURE.mkdir(parents=True, exist_ok=True)
    (FIXTURE / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


def metrics(candidate: np.ndarray, reference: np.ndarray) -> dict[str, float | int]:
    error = np.abs(candidate.astype(np.float64) - reference.astype(np.float64))
    return {
        "changed_voxels": int(np.count_nonzero(candidate != reference)),
        "max_absolute_error": float(error.max(initial=0)),
        "mean_absolute_error": float(error.mean()),
        "sign_differences": int(np.count_nonzero(np.signbit(candidate) != np.signbit(reference))),
        "dice": dice_coefficient(candidate <= 0, reference <= 0),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--import-java-json", type=Path, help="convert selected Java harness JSON into committed RAS NIfTI fixtures")
    args = parser.parse_args()
    if args.import_java_json:
        import_java_json(args.import_java_json)

    outer = load_volume(FIXTURE / "inputs/outer_level_set.nii.gz")
    inner = load_volume(FIXTURE / "inputs/inner_level_set.nii.gz")
    gray = load_volume(FIXTURE / "inputs/gray_matter.nii.gz")
    result = dura_tgdm_evolve(
        outer,
        gray,
        inner,
        membership_level=0.4,
        alpha=0.5,
        alignment_force=1.0,
        curvature_force=0.5,
        pressure_force=0.5,
        outer_iterations=5,
        record_passes=True,
    )
    java_dir = FIXTURE / "java_reference"
    pass_results = []
    for index, values in enumerate(result.pass_level_sets, start=1):
        ref = load_volume(java_dir / f"pass_{index:02d}.nii.gz")
        pass_results.append(metrics(values, ref))
    pre_results = []
    for index, values in enumerate(result.pre_reinitialization_level_sets, start=1):
        ref = load_volume(java_dir / f"pass_{index:02d}_pre_reinitialization.nii.gz")
        pre_results.append(metrics(values, ref))
    expected = load_volume(java_dir / "final.nii.gz")
    candidate = np.asarray(result.level_set, dtype=np.float32)
    candidate_vertices, candidate_faces, _, _ = marching_cubes(candidate, level=0.0)
    expected_vertices, expected_faces, _, _ = marching_cubes(expected, level=0.0)
    final_surface = mesh_surface_distance_metrics(candidate_vertices, candidate_faces, expected_vertices, expected_faces)
    report = {
        "synthetic_only": True,
        "shape": list(SHAPE),
        "completed_steps": result.completed_steps,
        "completed_outer_passes": result.completed_outer_passes,
        "landmine_restarts": result.landmine_restarts,
        "pass_metrics": pass_results,
        "pre_reinitialization_metrics": pre_results,
        "final_metrics": metrics(candidate, expected),
        "final_surface_metrics_mm": final_surface,
        "criteria": {"dice_minimum": 0.97, "symmetric_mean_surface_distance_mm_maximum": 0.01, "symmetric_hausdorff_mm_maximum": 1.0},
    }
    report["passed"] = (
        result.completed_outer_passes == 5
        and report["final_metrics"]["dice"] >= 0.97
        and final_surface["mean_absolute_distance_mm"] <= 0.01
        and final_surface["hausdorff_mm"] <= 1.0
    )
    print(json.dumps(report, indent=2, sort_keys=True))
    if not report["passed"]:
        raise SystemExit("folded-cortex Dura TGDM comparison failed agreed metrics")


if __name__ == "__main__":
    main()
