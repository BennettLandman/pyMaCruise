"""Deterministic synthetic inputs for PyMaCRUISE development and validation."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

import nibabel as nib
import numpy as np
import numpy.typing as npt

Array = npt.NDArray[np.generic]


def make_synthetic_phantom(seed: int = 20260927) -> tuple[dict[str, Array], np.ndarray, dict[str, Any]]:
    """Build deterministic nested tissue, lesion, and bias-field volumes.

    The main phantom uses anisotropic, mildly oblique voxel axes with RAS
    orientation. It includes separate non-RAS image data in the saved fixture
    set so input-normalization behavior can be checked.
    """
    shape = (32, 28, 24)
    i, j, k = np.indices(shape, dtype=np.float32)
    center = np.array([(n - 1) / 2 for n in shape], dtype=np.float32)
    x = (i - center[0]) / 1.0
    y = (j - center[1]) / 1.25
    z = (k - center[2]) / 1.5

    r_wm = (x / 7.0) ** 2 + (y / 6.5) ** 2 + (z / 5.5) ** 2
    r_gm = (x / 12.0) ** 2 + (y / 10.0) ** 2 + (z / 8.0) ** 2
    wm_envelope = r_wm <= 1.0
    cavity = (
        ((i - center[0] - 1.5) / 1.4) ** 2
        + ((j - center[1]) / 1.6) ** 2
        + ((k - center[2]) / 1.5) ** 2
        <= 1.0
    ) & wm_envelope
    wm = wm_envelope & ~cavity
    gm = (r_gm <= 1.0) & ~wm_envelope
    brain = wm | gm

    # A small asymmetric lesion sits on one side of the otherwise nested phantom.
    lesion = (
        ((i - (center[0] + 5)) / 2.0) ** 2
        + ((j - (center[1] - 2)) / 2.5) ** 2
        + ((k - center[2]) / 2.0) ** 2
        <= 1.0
    ) & gm

    labels = np.zeros(shape, dtype=np.uint16)
    labels[wm] = 4
    labels[gm] = 100

    rng = np.random.default_rng(seed)
    bias = (0.88 + 0.24 * i / (shape[0] - 1)).astype(np.float32)
    noise = rng.normal(0.0, 1.5, size=shape).astype(np.float32)
    tissue = np.zeros(shape, dtype=np.float32)
    tissue[wm] = 110.0
    tissue[gm] = 78.0
    tissue[lesion] = 92.0
    t1 = np.maximum(0.0, tissue * bias + noise).astype(np.float32)

    flair_base = np.zeros(shape, dtype=np.float32)
    flair_base[wm] = 55.0
    flair_base[gm] = 75.0
    flair_base[lesion] = 145.0
    flair_noise = rng.normal(0.0, 1.0, size=shape).astype(np.float32)
    flair = np.maximum(0.0, flair_base * bias + flair_noise).astype(np.float32)

    angle = np.deg2rad(7.0)
    c, s = float(np.cos(angle)), float(np.sin(angle))
    affine = np.array(
        [
            [c, -1.25 * s, 0.0, -15.0],
            [s, 1.25 * c, 0.0, -18.0],
            [0.0, 0.0, 1.5, -17.25],
            [0.0, 0.0, 0.0, 1.0],
        ],
        dtype=np.float64,
    )
    transform_angle = np.deg2rad(2.0)
    tc, ts = float(np.cos(transform_angle)), float(np.sin(transform_angle))
    transform = np.array(
        [
            [tc, -ts, 0.0, 2.0],
            [ts, tc, 0.0, -1.0],
            [0.0, 0.0, 1.0, 0.5],
            [0.0, 0.0, 0.0, 1.0],
        ],
        dtype=np.float64,
    )
    arrays: dict[str, Array] = {
        "T1": t1,
        "FLAIR": flair,
        "MaSeg": labels,
        "WM_mask": wm.astype(np.uint8),
        "GM_mask": gm.astype(np.uint8),
        "brain_mask": brain.astype(np.uint8),
        "lesion_mask": lesion.astype(np.uint8),
        "cavity_mask": cavity.astype(np.uint8),
        "bias_field": bias,
    }
    metadata: dict[str, Any] = {
        "provenance": "synthetic; generated by pymacruise.synthetic",
        "seed": int(seed),
        "shape": list(shape),
        "spacing_mm": [1.0, 1.25, 1.5],
        "orientation": "RAS; 7 degree in-plane obliquity",
        "world_coordinate_frame": "RAS+ millimetres",
        "affine": affine.tolist(),
        "labels": {"background": 0, "white_matter": 4, "gray_matter": 100},
        "lesion_representation": "separate binary mask; MaSeg labels are not repurposed",
        "cavity_representation": "background cavity within the white-matter envelope",
        "transform_RAS_mm": transform.tolist(),
        "recipe": "nested ellipsoids, asymmetric lesion, smooth multiplicative bias, seeded Gaussian noise",
        "license": "Project-generated synthetic fixture; no human or source-subject data.",
    }
    return arrays, affine, metadata


def _make_icosphere(subdivisions: int = 2) -> tuple[np.ndarray, np.ndarray]:
    """Create a closed unit icosphere without depending on a rendering stack."""
    golden = (1.0 + np.sqrt(5.0)) / 2.0
    vertices = np.array(
        [
            (-1, golden, 0), (1, golden, 0), (-1, -golden, 0), (1, -golden, 0),
            (0, -1, golden), (0, 1, golden), (0, -1, -golden), (0, 1, -golden),
            (golden, 0, -1), (golden, 0, 1), (-golden, 0, -1), (-golden, 0, 1),
        ],
        dtype=np.float64,
    )
    vertices /= np.linalg.norm(vertices, axis=1, keepdims=True)
    faces = np.array(
        [
            (0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11),
            (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
            (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9),
            (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1),
        ],
        dtype=np.int32,
    )

    for _ in range(subdivisions):
        midpoint_cache: dict[tuple[int, int], int] = {}
        next_vertices = vertices.tolist()

        def midpoint(first: int, second: int) -> int:
            key = tuple(sorted((first, second)))
            if key not in midpoint_cache:
                point = (vertices[first] + vertices[second]) / 2.0
                point /= np.linalg.norm(point)
                midpoint_cache[key] = len(next_vertices)
                next_vertices.append(point.tolist())
            return midpoint_cache[key]

        next_faces = []
        for first, second, third in faces:
            ab = midpoint(int(first), int(second))
            bc = midpoint(int(second), int(third))
            ca = midpoint(int(third), int(first))
            next_faces.extend(
                ((first, ab, ca), (second, bc, ab), (third, ca, bc), (ab, bc, ca))
            )
        vertices = np.asarray(next_vertices, dtype=np.float64)
        faces = np.asarray(next_faces, dtype=np.int32)
    return vertices, faces


def _save_nifti(path: Path, data: Array, affine: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image = nib.Nifti1Image(data, affine)
    image.set_sform(affine, code=1)
    image.set_qform(affine, code=1)
    nib.save(image, str(path))


def write_synthetic_fixtures(output_dir: str | Path, seed: int = 20260927) -> dict[str, Any]:
    """Write the deterministic phantom as compressed NIfTI plus JSON metadata."""
    root = Path(output_dir)
    arrays, affine, metadata = make_synthetic_phantom(seed)
    for name, data in arrays.items():
        _save_nifti(root / f"{name}.nii.gz", data, affine)

    # Tiny asymmetric LPS-oriented fixture with unique corner markers.
    non_ras = np.zeros((5, 7, 9), dtype=np.uint8)
    non_ras[0, 0, 0] = 1
    non_ras[4, 6, 8] = 2
    lps_affine = np.diag([-2.0, -1.5, 1.0, 1.0])
    lps_affine[:3, 3] = [8.0, 9.0, -4.0]
    _save_nifti(root / "non_ras_orientation.nii.gz", non_ras, lps_affine)

    boundary = np.zeros((8, 8, 8), dtype=np.uint16)
    boundary[:4, :, :] = 4
    boundary[4:, :, :] = 100
    boundary[3:5, 3:5, 3:5] = 55
    _save_nifti(root / "boundary_labels.nii.gz", boundary, affine)

    disconnected = np.zeros((16, 16, 16), dtype=np.uint16)
    disconnected[2:5, 2:5, 2:5] = 100
    disconnected[10:13, 10:13, 10:13] = 100
    disconnected[6:9, 6:9, 6:9] = 4
    _save_nifti(root / "disconnected_labels.nii.gz", disconnected, affine)

    unit_vertices, faces = _make_icosphere(subdivisions=2)
    center = (np.asarray(arrays["brain_mask"].shape, dtype=np.float64) - 1.0) / 2.0
    vertices_ijk = center + unit_vertices * np.array([12.0, 10.0, 8.0])
    vertices_ras = nib.affines.apply_affine(affine, vertices_ijk)
    np.savez_compressed(
        root / "brain_surface_ras.npz",
        vertices_ras_mm=vertices_ras.astype(np.float32),
        faces=faces.astype(np.int32),
    )

    metadata["non_ras_fixture"] = {
        "filename": "non_ras_orientation.nii.gz",
        "shape": list(non_ras.shape),
        "orientation": "LPS",
        "markers": {"voxel_000": 1, "voxel_468": 2},
        "purpose": "exercise warning and axis reorientation to RAS",
    }
    root.mkdir(parents=True, exist_ok=True)
    (root / "phantom.json").write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    checksum_lines = []
    for path in sorted(p for p in root.iterdir() if p.is_file() and p.name != "SHA256SUMS"):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        checksum_lines.append(f"{digest}  {path.name}")
    (root / "SHA256SUMS").write_text("\n".join(checksum_lines) + "\n", encoding="ascii")
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=20260927)
    args = parser.parse_args()
    metadata = write_synthetic_fixtures(args.output, seed=args.seed)
    print(json.dumps({"output": str(args.output), "seed": metadata["seed"]}, sort_keys=True))


if __name__ == "__main__":
    main()
