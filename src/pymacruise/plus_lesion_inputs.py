"""Prepare selected LesionTOADS products for the MaCRUISEplus crop stage.

This is a workflow adapter, not a registration algorithm. It consumes the
selected ``dura removal inputs`` channel product, transfers only GM, WM-fill,
and WM-mask to the Seg reference grid, then applies the shared crop derived
from multi-atlas GM to those images and the fixed plus companions. The CSF
channel is generated by LesionTOADS but is not returned by
``run_LesionToads_pipeline`` in the selected MaCRUISEplus route.
"""

from __future__ import annotations

from dataclasses import dataclass

import nibabel as nib
import numpy as np

from .cropping import CropParameters, crop_image, find_crop_parameters
from .image_io import normalize_image_to_ras
from .lesion_post_loop_outputs import LesionToadsPostLoopOutputs
from .spatial_transfer import transfer_to_reference_space


@dataclass(frozen=True)
class PlusLesionCroppedInputs:
    """Crop-ready maps handed from LesionTOADS into plus pre-TGDM stages."""

    multi_atlas_gm: nib.spatialimages.SpatialImage
    multi_atlas_wm: nib.spatialimages.SpatialImage
    multi_atlas_mask: nib.spatialimages.SpatialImage
    brain_mask: nib.spatialimages.SpatialImage
    segmentation: nib.spatialimages.SpatialImage
    toads_gm: nib.spatialimages.SpatialImage
    toads_wm_fill: nib.spatialimages.SpatialImage
    toads_wm_mask: nib.spatialimages.SpatialImage
    crop_parameters: CropParameters


def prepare_plus_lesion_inputs(
    lesion_outputs: LesionToadsPostLoopOutputs,
    lesion_output_grid: nib.spatialimages.SpatialImage,
    segmentation: nib.spatialimages.SpatialImage,
    multi_atlas_gm: nib.spatialimages.SpatialImage,
    multi_atlas_wm: nib.spatialimages.SpatialImage,
    multi_atlas_mask: nib.spatialimages.SpatialImage,
    brain_mask: nib.spatialimages.SpatialImage,
    *,
    crop_edge_width: int = 5,
) -> PlusLesionCroppedInputs:
    """Transfer P39 GM/WM products, then crop all selected plus companions.

    ``lesion_output_grid`` supplies the affine and shape for the arrays emitted
    by the P39 in-memory adapter. ``segmentation`` is both the selected STEP3
    transfer reference and one of the STEP4 crop targets. All remaining
    companions are expected on that same reference grid. Multi-atlas GM alone
    determines source-compatible bounds (strictly positive support plus the
    selected five-voxel default border).

    The selected JIST transfer uses ``ReorientVolume.solve`` with unchanged
    resolution and nearest-neighbor interpolation, then assigns the reference
    header. This adapter uses the repository's physical-affine nearest-neighbor
    transfer helper. The two are checked against the selected source for the
    identity RAS grid used here; differing origins, dimensions, or spacings are
    not claimed to reproduce JIST's orientation-only operation.
    """
    if not isinstance(lesion_outputs, LesionToadsPostLoopOutputs):
        raise TypeError("lesion_outputs must be LesionToadsPostLoopOutputs")
    if lesion_outputs.result_mode != "dura removal inputs":
        raise ValueError("plus preparation requires P39 dura removal inputs")
    if not isinstance(lesion_output_grid, (nib.Nifti1Image, nib.Nifti2Image)):
        raise TypeError("lesion_output_grid must be a NIfTI image")
    supplied_images = {
        "segmentation": segmentation,
        "multi_atlas_gm": multi_atlas_gm,
        "multi_atlas_wm": multi_atlas_wm,
        "multi_atlas_mask": multi_atlas_mask,
        "brain_mask": brain_mask,
    }
    if any(not isinstance(image, (nib.Nifti1Image, nib.Nifti2Image)) for image in supplied_images.values()):
        raise TypeError("all plus preparation companions must be NIfTI images")
    images = {
        name: normalize_image_to_ras(image, source_name=name)
        for name, image in supplied_images.items()
    }

    products = [product for product in lesion_outputs.products if product.name == "dura_removal_inputs"]
    if len(products) != 1:
        raise ValueError("P39 output must contain exactly one dura_removal_inputs product")
    channels = np.asarray(products[0].values, dtype=np.float32)
    if channels.ndim != 4 or channels.shape[0] != 4:
        raise ValueError("dura_removal_inputs must have shape [4, x, y, z]")
    if tuple(channels.shape[1:]) != tuple(lesion_output_grid.shape):
        raise ValueError("P39 output channels must match lesion_output_grid dimensions")

    transferred = []
    for channel_index in (1, 2, 3):
        channel_header = lesion_output_grid.header.copy()
        channel_header.set_data_dtype(np.float32)
        channel_header.set_slope_inter(None, None)
        channel_image = nib.Nifti1Image(
            channels[channel_index],
            lesion_output_grid.affine,
            header=channel_header,
        )
        transferred.append(
            transfer_to_reference_space(channel_image, segmentation, cval=0.0)
        )

    reference = images["segmentation"]
    multi_atlas_gm = images["multi_atlas_gm"]
    multi_atlas_wm = images["multi_atlas_wm"]
    multi_atlas_mask = images["multi_atlas_mask"]
    brain_mask = images["brain_mask"]
    segmentation = images["segmentation"]
    _require_same_grid("multi_atlas_gm", multi_atlas_gm, reference)
    for name, image in images.items():
        _require_same_grid(name, image, reference)
    for name, image in zip(("toads_gm", "toads_wm_fill", "toads_wm_mask"), transferred, strict=True):
        _require_same_grid(name, image, reference)

    crop = find_crop_parameters(multi_atlas_gm, threshold=0.0, edge_width=crop_edge_width)
    cropped = {
        name: crop_image(image, crop)
        for name, image in (
            ("multi_atlas_gm", multi_atlas_gm),
            ("multi_atlas_wm", multi_atlas_wm),
            ("multi_atlas_mask", multi_atlas_mask),
            ("brain_mask", brain_mask),
            ("segmentation", segmentation),
            ("toads_gm", transferred[0]),
            ("toads_wm_fill", transferred[1]),
            ("toads_wm_mask", transferred[2]),
        )
    }
    return PlusLesionCroppedInputs(**cropped, crop_parameters=crop)


def _require_same_grid(
    name: str,
    image: nib.spatialimages.SpatialImage,
    reference: nib.spatialimages.SpatialImage,
) -> None:
    if image.shape != reference.shape or not np.allclose(
        image.affine, reference.affine, rtol=0.0, atol=1e-5
    ):
        raise ValueError(f"{name} must share the segmentation reference grid")
    if nib.aff2axcodes(image.affine) != ("R", "A", "S"):
        raise ValueError(f"{name} must be RAS after input normalization")
